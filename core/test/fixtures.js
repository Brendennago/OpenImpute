import { writeFileSync, mkdtempSync } from 'node:fs';
import { gzipSync, deflateRawSync } from 'node:zlib';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { simulatePanel } from '../src/simulate.js';
import { formatVcfLine } from '../src/vcf.js';

const COMP = { A: 'T', T: 'A', C: 'G', G: 'C' };

/** Minimal single-entry zip writer (deflate) for tests. */
export function makeZip(name, content) {
  const data = Buffer.from(content);
  const comp = deflateRawSync(data);
  const crc = crc32(data);
  const nameBuf = Buffer.from(name);
  const local = Buffer.alloc(30);
  local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(8, 8);
  local.writeUInt32LE(crc, 14); local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22);
  local.writeUInt16LE(nameBuf.length, 26);
  const central = Buffer.alloc(46);
  central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(8, 10);
  central.writeUInt32LE(crc, 16); central.writeUInt32LE(comp.length, 20); central.writeUInt32LE(data.length, 24);
  central.writeUInt16LE(nameBuf.length, 28); central.writeUInt32LE(0, 42);
  const cdOffset = local.length + nameBuf.length + comp.length;
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0); eocd.writeUInt16LE(1, 8); eocd.writeUInt16LE(1, 10);
  eocd.writeUInt32LE(central.length + nameBuf.length, 12); eocd.writeUInt32LE(cdOffset, 16);
  return Buffer.concat([local, nameBuf, comp, central, nameBuf, eocd]);
}

function crc32(buf) {
  let c, crc = 0xffffffff;
  for (const b of buf) {
    c = (crc ^ b) & 0xff;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/**
 * Build a simulated panel VCF.gz (GRCh38-like coordinates) and a 23andMe-style
 * raw file for one held-out person (GRCh37-like coordinates, shifted), with
 * some SNPs reported on the opposite strand.
 */
export function makeFixture({ chipEvery = 8, heldOut = 0, flipEvery = 7 } = {}) {
  const dir = mkdtempSync(join(tmpdir(), 'openimpute-test-'));
  const { variants, samples } = simulatePanel({ nSamples: 201, nSites: 1500, seed: 7 });
  const keep = samples.map((_, i) => i).filter((i) => i !== heldOut);
  const panelVariants = variants.map((v) => {
    const haps = new Uint8Array(keep.length * 2);
    keep.forEach((s, k) => { haps[2 * k] = v.haps[2 * s]; haps[2 * k + 1] = v.haps[2 * s + 1]; });
    return { ...v, haps };
  });
  const header = [
    '##fileformat=VCFv4.2', '##contig=<ID=chr22>', '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">',
    ['#CHROM', 'POS', 'ID', 'REF', 'ALT', 'QUAL', 'FILTER', 'INFO', 'FORMAT', ...keep.map((s) => samples[s])].join('\t'),
  ];
  const vcf = [...header, ...panelVariants.map(formatVcfLine)].join('\n') + '\n';
  const panelPath = join(dir, 'panel.vcf.gz');
  writeFileSync(panelPath, gzipSync(vcf));

  const truth = new Map();
  const rows = ['# This data file generated by 23andMe', '# We are using reference human assembly build 37', '# rsid\tchromosome\tposition\tgenotype'];
  variants.forEach((v, i) => {
    const a = v.haps[2 * heldOut], b = v.haps[2 * heldOut + 1];
    truth.set(v.id, a + b);
    if (i % chipEvery !== 0) return;
    let gt = (a ? v.alt : v.ref) + (b ? v.alt : v.ref);
    const ambiguous = COMP[v.ref] === v.alt;
    if (i % flipEvery === 0 && !ambiguous) gt = [...gt].map((l) => COMP[l]).join('');
    rows.push([v.id, '22', v.pos - 12345, gt].join('\t')); // shifted coordinates: matching must use rsIDs
  });
  const dnaText = rows.join('\n') + '\n';
  const dnaPath = join(dir, 'genome.txt');
  writeFileSync(dnaPath, dnaText);
  const zipPath = join(dir, 'genome.zip');
  writeFileSync(zipPath, makeZip('genome_Test_v5.txt', dnaText));
  return { dir, panelPath, dnaPath, zipPath, variants, truth, chipEvery };
}
